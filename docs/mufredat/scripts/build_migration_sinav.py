"""sinav_dagilim_donem1_2026_2027.csv -> supabase/migrations/20261084000000_mufredat_sinav_dagilim.sql

Tablo: public.mufredat_sinav_dagilim (ders x sinif x sinav x senaryo x kazanim). Salt okunur referans; yazma yalnizca service_role.
Ek: dkab8_kod_eslesme.csv icinde 'eslesti' olan DKAB 8 kodlari icin mufredat_hafta.kazanim_kodu guncellemesi
(yalniz kazanim_kodu bos olan ve plan ilk cumlesi tam olarak bir kazanim grubuna denk gelen satirlar).
Calistirma: python -X utf8 build_migration_sinav.py <docs/mufredat> <repo-kok>
"""
import csv
import os
import re
import sys
from collections import Counter

DOC, REPO = sys.argv[1], sys.argv[2]
OUT = os.path.join(REPO, 'supabase', 'migrations', '20261084000000_mufredat_sinav_dagilim.sql')
SRC = os.path.join(DOC, 'sinav_dagilim_donem1_2026_2027.csv')
PLAN = os.path.join(DOC, 'haftalik_akis_2026_2027.csv')
ESLE = os.path.join(DOC, 'dkab8_kod_eslesme.csv')
DERS = 'Din Kültürü ve Ahlak Bilgisi'


def lit(v):
    if v is None or v == '':
        return 'null'
    return "'" + str(v).replace("'", "''") + "'"


def ltxt(v, ad):
    if v is None or v == '':
        raise SystemExit('zorunlu alan bos: ' + ad)
    return lit(v)


tum_satirlar = list(csv.DictReader(open(SRC, encoding='utf-8-sig')))
# Karar (koordinator): senaryosu bos (1318) ve MEB bildirim metinli (27) satirlar alinmaz; hepsinin soru_sayisi=0.
rows = [r for r in tum_satirlar if r['senaryo'].startswith('Senaryo ')]
dislanan = [r for r in tum_satirlar if not r['senaryo'].startswith('Senaryo ')]
if any(int(r['soru_sayisi']) for r in dislanan):
    raise SystemExit('dislanan satirda soru var; durdu')
print('dislanan satir', len(dislanan), 'kalan', len(rows))
anahtar = Counter((r['ders'], r['sinif'], r['sinav'], r['senaryo'], r['kazanim_kodu']) for r in rows)
tekrar = [k for k, v in anahtar.items() if v > 1]
if tekrar:
    raise SystemExit('benzersiz anahtar ihlali: %d ornek %s' % (len(tekrar), tekrar[:3]))

values = []
for r in rows:
    sc = r['soru_sayisi'].strip()
    if not sc.isdigit():
        raise SystemExit('soru_sayisi sayi degil: %r' % r)
    values.append('(' + ','.join([
        ltxt(r['ders'], 'ders'), str(int(r['sinif'])), ltxt(r['sinav'], 'sinav'), ltxt(r['senaryo'], 'senaryo'),
        lit(r['unite']), lit(r['konu']), ltxt(r['kazanim_kodu'], 'kazanim_kodu'), lit(r['kazanim_metni']),
        str(int(sc)),
    ]) + ')')

head = """-- Hupo: 2026-2027 1. donem ortak yazili sinav dagilimi (MEB kaynakli referans).
-- Kaynak: docs/mufredat/sinav_dagilim_donem1_2026_2027.csv (ODSGM 1. Donem Konu Soru Dagilim Tablolari 2026-2027).
-- Taslak veridir; MEB guncelleyebilir. Salt okunur referans; yazma yalnizca service_role.
-- Veri uretici: docs/mufredat/scripts/build_migration_sinav.py

create table if not exists public.mufredat_sinav_dagilim (
  id            bigint generated by default as identity primary key,
  ders          text not null,
  sinif         smallint not null check (sinif between 5 and 8),
  sinav         text not null,
  senaryo       text not null,
  unite         text,
  konu          text,
  kazanim_kodu  text not null,
  kazanim_metni text,
  soru_sayisi   smallint not null default 0,
  olusturma     timestamptz not null default now(),
  unique (ders, sinif, sinav, senaryo, kazanim_kodu)
);

comment on table public.mufredat_sinav_dagilim is 'MEB 2026-2027 1. donem ortak yazili soru dagilimi (ders x sinif x sinav x senaryo x kazanim); soru sayisi referansi. Salt okunur.';

create index if not exists mufredat_sinav_dagilim_ders_sinif_kazanim_idx on public.mufredat_sinav_dagilim (ders, sinif, kazanim_kodu);

alter table public.mufredat_sinav_dagilim enable row level security;

drop policy if exists mufredat_sinav_dagilim_okuma on public.mufredat_sinav_dagilim;
create policy mufredat_sinav_dagilim_okuma on public.mufredat_sinav_dagilim
  for select to authenticated using (true);

revoke all on public.mufredat_sinav_dagilim from public, anon, authenticated;
grant select on public.mufredat_sinav_dagilim to authenticated;
grant select, insert, update, delete on public.mufredat_sinav_dagilim to service_role;

-- Veri
"""

CHUNK = 400
body = []
for i in range(0, len(values), CHUNK):
    body.append('insert into public.mufredat_sinav_dagilim (ders, sinif, sinav, senaryo, unite, konu, kazanim_kodu, kazanim_metni, soru_sayisi) values\n'
                + ',\n'.join(values[i:i + CHUNK]) + '\non conflict (ders, sinif, sinav, senaryo, kazanim_kodu) do nothing;\n')

# --- DKAB 8 kod guncellemesi (yalniz eslesti) ---
def ilk_cumle(metin):
    parca = (metin or '').split(' / ')[0].strip()
    return re.sub(r'^\s*\d+\s*\.\s*', '', parca).strip()


plan_rows = [r for r in csv.DictReader(open(PLAN, encoding='utf-8-sig'))
             if r['ders'] == DERS and r['sinif'] == '8' and r['kaynak_yili'] == '2025-2026']
esle = [r for r in csv.DictReader(open(ESLE, encoding='utf-8-sig')) if r['durum'] in ('eslesti', 'eslesti_yazim')]

upd = []
for r in esle:
    kod, pattern = r['kod'], r['plan_metni']
    not_eki = 'kod_sinav_tablosu_yazim_normalizasyonu' if r['durum'] == 'eslesti_yazim' else 'kod_sinav_tablosu_metin_eslesmesi'
    if not pattern or '%' in pattern or '_' in pattern or '\\' in pattern:
        raise SystemExit('desen guvensiz: %r' % pattern)
    if True:
        # satirlar: ilk cumlesi tam bu olan grup; desen baska gruba da denk geliyor mu?
        grup = [p for p in plan_rows if ilk_cumle(p['kazanim_metni']) == pattern]
        denk = [p for p in plan_rows if pattern in (p['kazanim_metni'] or '') and p['kazanim_kodu'] == '']
        if not grup or len(grup) != len(denk):
            raise SystemExit('desen grup disi satirla eslesiyor: %s grup=%d denk=%d' % (kod, len(grup), len(denk)))
    upd.append((kod, pattern, len(grup), not_eki))

body.append('-- DKAB 8: kod atamasi (yalniz metin eslesmesi; docs/mufredat/dkab8_kod_eslesme.csv)\n')
for kod, pattern, n, not_eki in upd:
    body.append(
        "update public.mufredat_hafta set kazanim_kodu = %s,\n"
        "  kayit_notu = case when kayit_notu = '' then '%s' else kayit_notu || ';%s' end\n"
        "where ders = %s and sinif = 8 and kaynak_yili = '2025-2026' and kazanim_kodu = ''\n"
        "  and kazanim_metni like %s;\n" % (lit(kod), not_eki, not_eki, lit(DERS), lit('%' + pattern + '%')))

open(OUT, 'w', encoding='utf-8', newline='\n').write(head + '\n'.join(body))
print('yazildi', OUT, 'sinav satir', len(values), 'dkab8 guncelleme', len(upd),
      'guncellenecek satir', sum(u[2] for u in upd), 'bayt', os.path.getsize(OUT))

