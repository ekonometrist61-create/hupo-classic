"""haftalik_akis_2026_2027.csv -> supabase/migrations/20261083000000_mufredat_hafta.sql

Tablo: public.mufredat_hafta (ders x sinif x hafta x kazanim). Salt okunur referans; yazma yalnizca service_role.
Calistirma: python -X utf8 build_migration.py <docs/mufredat> <repo-kok>
"""
import csv
import collections
import os
import sys

DOC, REPO = sys.argv[1], sys.argv[2]
OUT = os.path.join(REPO, 'supabase', 'migrations', '20261083000000_mufredat_hafta.sql')
SRC = os.path.join(DOC, 'haftalik_akis_2026_2027.csv')


def lit(v):
    if v is None or v == '':
        return 'null'
    return "'" + str(v).replace("'", "''") + "'"


def ltxt(v):
    # zorunlu (not null) metin sutunlari: bos deger null degil '' yazilir
    return "''" if v in (None, '') else lit(v)


def num(v):
    return str(int(v)) if v not in (None, '') else 'null'


rows = list(csv.DictReader(open(SRC, encoding='utf-8-sig')))
seq = collections.Counter()
values = []
for r in rows:
    key = (r['ders'], r['sinif'], r['varyant'], r['kaynak_yili'], r['hafta'])
    seq[key] += 1
    values.append('(' + ','.join([
        ltxt(r['ders']), num(r['sinif']), ltxt(r['kaynak_yili']), ltxt(r['varyant']), ltxt(r['program']),
        num(r['hafta']), str(seq[key]), lit(r['baslangic']) if r['baslangic'] else 'null', lit(r['bitis']) if r['bitis'] else 'null',
        lit(r['ay']), lit(r['ders_saati']), lit(r['unite_tema']), lit(r['konu']), ltxt(r['kazanim_kodu']),
        lit(r['kazanim_metni']), lit(r['belirli_gun_hafta']), ltxt(r['kayit_notu']),
    ]) + ')')

head = """-- Hupo: 2026-2027 haftalik mufredat akisi (MEB kaynakli referans).
-- Kaynaklar: MEB TYMM taslak cerceve yillik planlar (tymm.meb.gov.tr, Temel Egitim sayfasi)
--            + dogm.meb.gov.tr DKAB planlari (5-7 2026-27; 4 ve 8 yalniz 2025-2026 dosyasi)
--            + kullanicinin verdigi 5. sinif DKAB plani.
-- Taslak plandir; MEB guncelleyebilir. Her satir bir hafta x bir kazanim (kodsuz satirlar kod uydurulmadan metinle tutulur).
-- kaynak_yili: 2025-2026 yalniz DKAB 4 ve 8 icin (2026-27 yayimi yok). program: kaynak sayfa etiketi / dogm isareti.
-- Veri uretici: docs/mufredat/scripts/build_migration.py (kaynak: docs/mufredat/haftalik_akis_2026_2027.csv).

create table if not exists public.mufredat_hafta (
  id            bigint generated by default as identity primary key,
  ders          text not null,
  sinif         smallint not null check (sinif between 1 and 8),
  kaynak_yili   text not null,
  varyant       text not null default '',
  program       text not null,
  hafta         smallint not null check (hafta between 1 and 60),
  sira          smallint not null default 1,
  baslangic     date,
  bitis         date,
  ay            text,
  ders_saati    text,
  unite_tema    text,
  konu          text,
  kazanim_kodu  text not null default '',
  kazanim_metni text,
  belirli_gun   text,
  kayit_notu    text not null default '',
  olusturma     timestamptz not null default now(),
  unique (ders, sinif, kaynak_yili, varyant, hafta, sira)
);

comment on table public.mufredat_hafta is 'MEB 2026-2027 haftalik mufredat akisi; soru etiketleme anahtari (kazanim_kodu + hafta). Salt okunur referans.';

create index if not exists mufredat_hafta_ders_sinif_hafta_idx on public.mufredat_hafta (ders, sinif, hafta);
create index if not exists mufredat_hafta_kazanim_idx on public.mufredat_hafta (kazanim_kodu) where kazanim_kodu <> '';

alter table public.mufredat_hafta enable row level security;

drop policy if exists mufredat_hafta_okuma on public.mufredat_hafta;
create policy mufredat_hafta_okuma on public.mufredat_hafta
  for select to authenticated using (true);

revoke all on public.mufredat_hafta from public, anon, authenticated;
grant select on public.mufredat_hafta to authenticated;
grant select, insert, update, delete on public.mufredat_hafta to service_role;

-- Veri
"""

CHUNK = 400
body = []
for i in range(0, len(values), CHUNK):
    body.append('insert into public.mufredat_hafta (ders, sinif, kaynak_yili, varyant, program, hafta, sira, baslangic, bitis, ay, ders_saati, unite_tema, konu, kazanim_kodu, kazanim_metni, belirli_gun, kayit_notu) values\n'
                + ',\n'.join(values[i:i + CHUNK]) + '\non conflict (ders, sinif, kaynak_yili, varyant, hafta, sira) do nothing;\n')

open(OUT, 'w', encoding='utf-8', newline='\n').write(head + '\n'.join(body))
print('yazildi', OUT, 'satir', len(values), 'bayt', os.path.getsize(OUT))
